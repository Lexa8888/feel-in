// Функция для получения вопроса на сегодня (без повторений)
export const getTodaysQuizQuestion = (lang, pairId) => {
  const today = new Date().toISOString().split('T')[0];
  const questions = QUIZ_QUESTIONS[lang];
  
  // Используем pairId + дату для генерации уникального индекса
  // Это гарантирует, что каждая пара получит свой вопрос, и он не повторится
  const seed = `${pairId}-${today}`;
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    const char = seed.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32bit integer
  }
  
  const questionIndex = Math.abs(hash) % questions.length;
  return questions[questionIndex];
};